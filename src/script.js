let lang = "en";
try { lang = localStorage.getItem("lang") || "en"; } catch (e) {}
const t = k => I18N[lang][k];

function setLang(l) {
  lang = I18N[l] ? l : "en";
  try { localStorage.setItem("lang", lang); } catch (e) {}
  const h = document.documentElement;
  h.lang = lang; h.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => { const v = t(el.dataset.i18n); if (v) el.textContent = v; });
  document.title = t("title");
  document.querySelector('meta[name=description]').content = t("desc");
  document.getElementById("lang").textContent = lang === "ar" ? "EN" : "AR";
  document.getElementById("ok").textContent = "";
  document.querySelectorAll("form em").forEach(e => e.textContent = "");
}

/* Nav: solid on scroll, mobile menu */
const nav = document.getElementById("nav"), menu = document.getElementById("menu"), burger = document.getElementById("burger");
const onScroll = () => nav.classList.toggle("solid", scrollY > 40 || menu.classList.contains("open"));
addEventListener("scroll", onScroll, { passive: true });
burger.addEventListener("click", () => {
  const open = menu.classList.toggle("open");
  burger.setAttribute("aria-expanded", open); onScroll();
});
menu.addEventListener("click", e => { if (e.target.tagName === "A") { menu.classList.remove("open"); burger.setAttribute("aria-expanded", false); onScroll(); } });
document.getElementById("lang").addEventListener("click", () => setLang(lang === "ar" ? "en" : "ar"));

/* Scroll reveal */
const rv = document.querySelectorAll(".rv");
if ("IntersectionObserver" in window) {
  const io = new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add("on"); io.unobserve(e.target); } }), { threshold: .12 });
  rv.forEach(el => io.observe(el));
} else rv.forEach(el => el.classList.add("on"));

/* Contact form: validates, then opens the visitor's email app (no backend) */
document.getElementById("form").addEventListener("submit", e => {
  e.preventDefault();
  const f = e.target; let ok = true;
  f.querySelectorAll("label").forEach(l => {
    const i = l.querySelector("input,textarea"), v = i.value.trim();
    let msg = "";
    if (!v) msg = t("e_req");
    else if (i.type === "email" && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v)) msg = t("e_mail");
    l.classList.toggle("bad", !!msg); l.querySelector("em").textContent = msg;
    if (msg) ok = false;
  });
  if (!ok) { f.querySelector(".bad input,.bad textarea").focus(); return; }
  const d = new FormData(f);
  const body = `${d.get("message")}\n\n${d.get("name")} <${d.get("email")}>`;
  location.href = `mailto:amalalghad.ltd.co@gmail.com?subject=${encodeURIComponent(d.get("subject"))}&body=${encodeURIComponent(body)}`;
  document.getElementById("ok").textContent = t("f_ok");
});

